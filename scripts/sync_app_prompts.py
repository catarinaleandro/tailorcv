#!/usr/bin/env python3
"""Copy the pipeline's prompts, rules, renderer and template into app/ so the web app uses exactly the same text and code.
Usage: python3 scripts/sync_app_prompts.py [--check]. With --check, exit 1 if app/ is out of date (no writes)."""
import sys, json, re, shutil, os, filecmp
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def body(path):
    t = open(os.path.join(R, path), encoding='utf8').read()
    return re.sub(r'\A---\n.*?\n---\n', '', t, count=1, flags=re.S).strip()
files = {
  'analyst': 'agents/job-analyst.md', 'matcher': 'agents/evidence-matcher.md', 'builder': 'agents/cv-builder.md',
  'auditor': 'agents/fabrication-auditor.md', 'summarySkill': 'skills/professional-summary/SKILL.md',
  'cvFormat': 'docs/CV_FORMAT.md', 'noFabrication': 'references/no-fabrication-policy.md', 'atsRules': 'references/ats-rules.md',
  'gapQuestions': 'references/gap-questions.md', 'fitRubric': 'references/fit-rubric.md',
}
js = '// GENERATED by scripts/sync_app_prompts.py from the repo files named in the comments. Do not edit by hand.\n'
for k, p in files.items():
    js += f'// {k}: {p}\nexport const {k} = {json.dumps(body(p))};\n'
copies = [('scripts/build_cv.py', 'app/api/_build_cv.py'), ('sample/IENYC_CV_Template.docx', 'app/api/IENYC_CV_Template.docx'), ('scripts/template_check.py', 'app/api/_template_check.py')]
if '--check' in sys.argv:
    ok = os.path.exists(os.path.join(R, 'app/lib/prompts.js')) and open(os.path.join(R, 'app/lib/prompts.js'), encoding='utf8').read() == js
    for s, d in copies:
        ok = ok and os.path.exists(os.path.join(R, d)) and filecmp.cmp(os.path.join(R, s), os.path.join(R, d), shallow=False)
    print('app in sync' if ok else 'app OUT OF DATE'); sys.exit(0 if ok else 1)
open(os.path.join(R, 'app/lib/prompts.js'), 'w', encoding='utf8').write(js)
for s, d in copies: shutil.copyfile(os.path.join(R, s), os.path.join(R, d))
print('synced', len(files), 'prompts and', len(copies), 'files')
